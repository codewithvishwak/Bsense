"""Streamlit frontend for Black Friday purchase prediction."""

from __future__ import annotations

from io import BytesIO

import pandas as pd
import streamlit as st

from black_friday_analysis import build_model, make_synthetic_data, prepare_data


st.set_page_config(page_title="Black Friday Sales Predictor", page_icon="🛍️", layout="centered")

st.title("Black Friday Sales Predictor")
st.write("Enter customer and product details to estimate the purchase amount.")


@st.cache_resource
def train_model(dataset: bytes | None):
    if dataset is None:
        raw = make_synthetic_data()
    else:
        raw = pd.read_csv(BytesIO(dataset))
    features, target = prepare_data(raw)
    model = build_model(features)
    model.fit(features, target)
    return model, features.columns.tolist(), len(raw)


with st.sidebar:
    st.header("Model data")
    uploaded_file = st.file_uploader(
        "Upload a Black Friday train.csv",
        type=["csv"],
        help="The file must contain a Purchase column. Without an upload, the demo model uses synthetic data.",
    )
    dataset_bytes = uploaded_file.getvalue() if uploaded_file is not None else None
    try:
        model, feature_columns, row_count = train_model(dataset_bytes)
    except (ValueError, KeyError, pd.errors.ParserError) as error:
        st.error(f"Could not load the dataset: {error}")
        st.stop()
    st.caption(f"Model trained on {row_count:,} rows.")
    if dataset_bytes is None:
        st.info("Demo mode: upload train.csv for real-data predictions.")

st.subheader("Customer details")
col1, col2 = st.columns(2)
with col1:
    gender = st.selectbox("Gender", ["F", "M"])
    age = st.selectbox("Age group", ["0-17", "18-25", "26-35", "36-45", "46-50", "51-55", "55+"])
    occupation = st.number_input("Occupation code", min_value=0, max_value=20, value=4, step=1)
    marital_status = st.selectbox("Marital status", [0, 1], format_func=lambda value: "Married" if value else "Single")
with col2:
    city_category = st.selectbox("City category", ["A", "B", "C"])
    stay = st.selectbox("Years in current city", ["0", "1", "2", "3", "4+"])
    user_id = st.number_input("User ID (optional)", min_value=0, value=100001, step=1)
    product_id = st.text_input("Product ID (optional)", value="P0001")

if st.button("Predict purchase amount", type="primary", use_container_width=True):
    input_row = pd.DataFrame(
        [
            {
                "User_ID": user_id,
                "Product_ID": product_id,
                "Gender": gender,
                "Age": age,
                "Occupation": str(occupation),
                "City_Category": city_category,
                "Stay_In_Current_City_Years": stay,
                "Marital_Status": marital_status,
            }
        ]
    )
    input_features = input_row.drop(columns=["User_ID", "Product_ID"])
    input_features = input_features.reindex(columns=feature_columns)
    prediction = float(model.predict(input_features)[0])
    st.success(f"Estimated purchase amount: ₹{prediction:,.0f}")
    st.caption("This estimate is generated by the trained Random Forest model and may vary from the actual purchase.")
